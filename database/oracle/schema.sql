CREATE TABLE fc_hotel (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(160) NOT NULL,
    timezone VARCHAR2(80) DEFAULT 'America/Sao_Paulo' NOT NULL,
    checkin_time VARCHAR2(5) DEFAULT '14:00' NOT NULL,
    checkout_time VARCHAR2(5) DEFAULT '12:00' NOT NULL,
    early_checkin_minutes NUMBER DEFAULT 120 NOT NULL,
    late_checkout_minutes NUMBER DEFAULT 60 NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

CREATE TABLE fc_room (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id NUMBER NOT NULL,
    room_number VARCHAR2(20) NOT NULL,
    room_type VARCHAR2(40) NOT NULL,
    status VARCHAR2(30) DEFAULT 'AVAILABLE' NOT NULL,
    floor_number NUMBER,
    CONSTRAINT fk_room_hotel FOREIGN KEY (hotel_id) REFERENCES fc_hotel(id),
    CONSTRAINT uk_room UNIQUE (hotel_id, room_number),
    CONSTRAINT ck_room_status CHECK (status IN ('AVAILABLE', 'OCCUPIED', 'CLEANING', 'MAINTENANCE', 'BLOCKED'))
);

CREATE TABLE fc_guest (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(180) NOT NULL,
    document_type VARCHAR2(30) NOT NULL,
    document_number VARCHAR2(60) NOT NULL,
    birth_date DATE,
    nationality VARCHAR2(80),
    email VARCHAR2(160),
    phone VARCHAR2(40),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT uk_guest_document UNIQUE (document_type, document_number)
);

CREATE TABLE fc_reservation (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id NUMBER NOT NULL,
    room_id NUMBER,
    reservation_code VARCHAR2(40) NOT NULL,
    pms_external_id VARCHAR2(80),
    status VARCHAR2(30) DEFAULT 'CONFIRMED' NOT NULL,
    arrival_date DATE NOT NULL,
    departure_date DATE NOT NULL,
    adults NUMBER DEFAULT 1 NOT NULL,
    children NUMBER DEFAULT 0 NOT NULL,
    total_amount NUMBER(12,2) DEFAULT 0 NOT NULL,
    currency VARCHAR2(3) DEFAULT 'BRL' NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_reservation_hotel FOREIGN KEY (hotel_id) REFERENCES fc_hotel(id),
    CONSTRAINT fk_reservation_room FOREIGN KEY (room_id) REFERENCES fc_room(id),
    CONSTRAINT uk_reservation_code UNIQUE (reservation_code),
    CONSTRAINT ck_reservation_status CHECK (status IN ('CONFIRMED', 'CANCELLED', 'NO_SHOW', 'CHECKED_IN', 'CHECKED_OUT')),
    CONSTRAINT ck_reservation_dates CHECK (departure_date > arrival_date)
);

CREATE TABLE fc_reservation_guest (
    reservation_id NUMBER NOT NULL,
    guest_id NUMBER NOT NULL,
    is_primary CHAR(1) DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_reservation_guest PRIMARY KEY (reservation_id, guest_id),
    CONSTRAINT fk_rg_reservation FOREIGN KEY (reservation_id) REFERENCES fc_reservation(id),
    CONSTRAINT fk_rg_guest FOREIGN KEY (guest_id) REFERENCES fc_guest(id),
    CONSTRAINT ck_rg_primary CHECK (is_primary IN ('Y', 'N'))
);

CREATE TABLE fc_kiosk_device (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hotel_id NUMBER NOT NULL,
    device_code VARCHAR2(60) NOT NULL,
    name VARCHAR2(120) NOT NULL,
    status VARCHAR2(30) DEFAULT 'OFFLINE' NOT NULL,
    last_seen_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_kiosk_hotel FOREIGN KEY (hotel_id) REFERENCES fc_hotel(id),
    CONSTRAINT uk_kiosk_code UNIQUE (device_code),
    CONSTRAINT ck_kiosk_status CHECK (status IN ('ONLINE', 'OFFLINE', 'MAINTENANCE', 'ERROR'))
);

CREATE TABLE fc_checkin_session (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kiosk_id NUMBER NOT NULL,
    reservation_id NUMBER,
    flow_type VARCHAR2(20) NOT NULL,
    status VARCHAR2(40) DEFAULT 'STARTED' NOT NULL,
    language VARCHAR2(10) DEFAULT 'pt-BR' NOT NULL,
    started_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    completed_at TIMESTAMP,
    failure_reason VARCHAR2(120),
    correlation_id VARCHAR2(80),
    CONSTRAINT fk_session_kiosk FOREIGN KEY (kiosk_id) REFERENCES fc_kiosk_device(id),
    CONSTRAINT fk_session_reservation FOREIGN KEY (reservation_id) REFERENCES fc_reservation(id),
    CONSTRAINT ck_session_flow CHECK (flow_type IN ('CHECKIN', 'CHECKOUT')),
    CONSTRAINT ck_session_status CHECK (status IN ('STARTED', 'RESERVATION_FOUND', 'DATA_CONFIRMED', 'PAYMENT_APPROVED', 'CHECKED_IN', 'CHECKED_OUT', 'FAILED', 'EXPIRED', 'HANDOFF'))
);

CREATE TABLE fc_consent (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id NUMBER NOT NULL,
    guest_id NUMBER NOT NULL,
    consent_type VARCHAR2(40) NOT NULL,
    accepted CHAR(1) NOT NULL,
    version VARCHAR2(30) NOT NULL,
    accepted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_consent_session FOREIGN KEY (session_id) REFERENCES fc_checkin_session(id),
    CONSTRAINT fk_consent_guest FOREIGN KEY (guest_id) REFERENCES fc_guest(id),
    CONSTRAINT ck_consent_type CHECK (consent_type IN ('PRIVACY_POLICY', 'HOSTING_TERMS', 'BIOMETRY', 'MARKETING')),
    CONSTRAINT ck_consent_accepted CHECK (accepted IN ('Y', 'N'))
);

CREATE TABLE fc_document_verification (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id NUMBER NOT NULL,
    guest_id NUMBER NOT NULL,
    status VARCHAR2(30) NOT NULL,
    provider VARCHAR2(60) DEFAULT 'MOCK' NOT NULL,
    reference_code VARCHAR2(120),
    verified_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_doc_session FOREIGN KEY (session_id) REFERENCES fc_checkin_session(id),
    CONSTRAINT fk_doc_guest FOREIGN KEY (guest_id) REFERENCES fc_guest(id),
    CONSTRAINT ck_doc_status CHECK (status IN ('APPROVED', 'REJECTED', 'MANUAL_REVIEW'))
);

CREATE TABLE fc_biometry_verification (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id NUMBER NOT NULL,
    guest_id NUMBER NOT NULL,
    status VARCHAR2(30) NOT NULL,
    provider VARCHAR2(60) DEFAULT 'MOCK' NOT NULL,
    template_reference VARCHAR2(160),
    score NUMBER(5,2),
    verified_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_bio_session FOREIGN KEY (session_id) REFERENCES fc_checkin_session(id),
    CONSTRAINT fk_bio_guest FOREIGN KEY (guest_id) REFERENCES fc_guest(id),
    CONSTRAINT ck_bio_status CHECK (status IN ('APPROVED', 'REJECTED', 'SKIPPED', 'MANUAL_REVIEW'))
);

CREATE TABLE fc_stay (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id NUMBER NOT NULL,
    room_id NUMBER NOT NULL,
    status VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
    checked_in_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expected_checkout_at TIMESTAMP NOT NULL,
    checked_out_at TIMESTAMP,
    CONSTRAINT fk_stay_reservation FOREIGN KEY (reservation_id) REFERENCES fc_reservation(id),
    CONSTRAINT fk_stay_room FOREIGN KEY (room_id) REFERENCES fc_room(id),
    CONSTRAINT uk_stay_reservation UNIQUE (reservation_id),
    CONSTRAINT ck_stay_status CHECK (status IN ('ACTIVE', 'PENDING_KEY', 'CHECKED_OUT', 'CANCELLED'))
);

CREATE TABLE fc_payment_transaction (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_id NUMBER,
    reservation_id NUMBER,
    transaction_type VARCHAR2(30) NOT NULL,
    status VARCHAR2(30) NOT NULL,
    amount NUMBER(12,2) NOT NULL,
    currency VARCHAR2(3) DEFAULT 'BRL' NOT NULL,
    provider VARCHAR2(60) DEFAULT 'MOCK' NOT NULL,
    authorization_code VARCHAR2(80),
    idempotency_key VARCHAR2(120),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_payment_stay FOREIGN KEY (stay_id) REFERENCES fc_stay(id),
    CONSTRAINT fk_payment_reservation FOREIGN KEY (reservation_id) REFERENCES fc_reservation(id),
    CONSTRAINT uk_payment_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_payment_type CHECK (transaction_type IN ('PRE_AUTH', 'CAPTURE', 'SALE', 'REFUND')),
    CONSTRAINT ck_payment_status CHECK (status IN ('APPROVED', 'DECLINED', 'PENDING', 'CANCELLED', 'ERROR'))
);

CREATE TABLE fc_key_credential (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stay_id NUMBER NOT NULL,
    room_id NUMBER NOT NULL,
    key_type VARCHAR2(30) NOT NULL,
    status VARCHAR2(30) NOT NULL,
    key_value VARCHAR2(160),
    issued_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    revoked_at TIMESTAMP,
    CONSTRAINT fk_key_stay FOREIGN KEY (stay_id) REFERENCES fc_stay(id),
    CONSTRAINT fk_key_room FOREIGN KEY (room_id) REFERENCES fc_room(id),
    CONSTRAINT ck_key_type CHECK (key_type IN ('DIGITAL', 'PHYSICAL')),
    CONSTRAINT ck_key_status CHECK (status IN ('ISSUED', 'ACTIVE', 'REVOKED', 'EXPIRED', 'FAILED'))
);

CREATE TABLE fc_device_event (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kiosk_id NUMBER NOT NULL,
    event_type VARCHAR2(60) NOT NULL,
    severity VARCHAR2(20) DEFAULT 'INFO' NOT NULL,
    message VARCHAR2(500),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_device_event_kiosk FOREIGN KEY (kiosk_id) REFERENCES fc_kiosk_device(id),
    CONSTRAINT ck_device_severity CHECK (severity IN ('INFO', 'WARN', 'ERROR'))
);

CREATE TABLE fc_pms_event (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id NUMBER,
    event_type VARCHAR2(80) NOT NULL,
    status VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    payload CLOB,
    attempts NUMBER DEFAULT 0 NOT NULL,
    last_attempt_at TIMESTAMP,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_pms_reservation FOREIGN KEY (reservation_id) REFERENCES fc_reservation(id),
    CONSTRAINT ck_pms_status CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'IGNORED'))
);

CREATE TABLE fc_audit_log (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type VARCHAR2(30) NOT NULL,
    actor_id VARCHAR2(80),
    action VARCHAR2(100) NOT NULL,
    resource_type VARCHAR2(80),
    resource_id VARCHAR2(80),
    result VARCHAR2(30) NOT NULL,
    correlation_id VARCHAR2(80),
    ip_address VARCHAR2(80),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT ck_audit_actor CHECK (actor_type IN ('GUEST', 'USER', 'KIOSK', 'SYSTEM')),
    CONSTRAINT ck_audit_result CHECK (result IN ('SUCCESS', 'FAILURE', 'DENIED'))
);

CREATE INDEX ix_reservation_dates ON fc_reservation(hotel_id, arrival_date, departure_date);
CREATE INDEX ix_session_status ON fc_checkin_session(status, started_at);
CREATE INDEX ix_stay_status ON fc_stay(status, checked_in_at);
CREATE INDEX ix_audit_correlation ON fc_audit_log(correlation_id);


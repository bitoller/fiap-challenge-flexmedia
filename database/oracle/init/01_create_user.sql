ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
    user_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO user_count FROM dba_users WHERE username = 'FLEXCHECK_APP';

    IF user_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER flexcheck_app IDENTIFIED BY "change_me_local_password"';
    END IF;

    EXECUTE IMMEDIATE 'GRANT CONNECT, RESOURCE TO flexcheck_app';
    EXECUTE IMMEDIATE 'GRANT UNLIMITED TABLESPACE TO flexcheck_app';
    EXECUTE IMMEDIATE 'ALTER USER flexcheck_app QUOTA UNLIMITED ON SYSTEM';
END;
/


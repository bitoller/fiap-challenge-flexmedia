ALTER SESSION SET CONTAINER = FREEPDB1;

DECLARE
    user_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO user_count FROM dba_users WHERE username = 'FLEXCHECK';

    IF user_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE USER FLEXCHECK IDENTIFIED BY flexcheck';
        EXECUTE IMMEDIATE 'GRANT CONNECT, RESOURCE TO FLEXCHECK';
        EXECUTE IMMEDIATE 'ALTER USER FLEXCHECK QUOTA UNLIMITED ON USERS';
    END IF;
END;
/


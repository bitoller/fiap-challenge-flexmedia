package br.com.fiap.flexcheck.checkin.infrastructure.repository;

import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
public class BiometricReferenceSchemaInitializer implements ApplicationRunner {
    private final JdbcTemplate jdbc;

    public BiometricReferenceSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(ApplicationArguments args) {
        executeIfMissing("""
                CREATE TABLE fc_biometric_reference (
                    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    session_id NUMBER NOT NULL,
                    reservation_id NUMBER NOT NULL,
                    guest_id NUMBER NOT NULL,
                    hotel_id NUMBER NOT NULL,
                    provider VARCHAR2(60) NOT NULL,
                    status VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
                    image_base64 CLOB NOT NULL,
                    mime_type VARCHAR2(80) DEFAULT 'image/jpeg' NOT NULL,
                    score NUMBER(5,2),
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    CONSTRAINT fk_bio_ref_session FOREIGN KEY (session_id) REFERENCES fc_checkin_session(id),
                    CONSTRAINT fk_bio_ref_reservation FOREIGN KEY (reservation_id) REFERENCES fc_reservation(id),
                    CONSTRAINT fk_bio_ref_guest FOREIGN KEY (guest_id) REFERENCES fc_guest(id),
                    CONSTRAINT fk_bio_ref_hotel FOREIGN KEY (hotel_id) REFERENCES fc_hotel(id),
                    CONSTRAINT ck_bio_ref_status CHECK (status IN ('ACTIVE', 'REVOKED'))
                )
                """);
        executeIfMissing("CREATE INDEX ix_bio_ref_guest ON fc_biometric_reference(hotel_id, guest_id, status)");
        executeIfMissing("CREATE INDEX ix_bio_ref_reservation ON fc_biometric_reference(reservation_id, status)");
    }

    private void executeIfMissing(String sql) {
        try {
            jdbc.execute(sql);
        } catch (Exception ignored) {
        }
    }
}

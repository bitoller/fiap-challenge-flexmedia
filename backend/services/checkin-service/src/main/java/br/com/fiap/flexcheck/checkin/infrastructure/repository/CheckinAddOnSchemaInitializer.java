package br.com.fiap.flexcheck.checkin.infrastructure.repository;

import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Component;

@Component
public class CheckinAddOnSchemaInitializer implements ApplicationRunner {
    private final JdbcTemplate jdbc;

    public CheckinAddOnSchemaInitializer(JdbcTemplate jdbc) {
        this.jdbc = jdbc;
    }

    @Override
    public void run(ApplicationArguments args) {
        executeIfMissing("""
                CREATE TABLE fc_reservation_addon (
                    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    reservation_id NUMBER NOT NULL,
                    session_id NUMBER NOT NULL,
                    code VARCHAR2(60) NOT NULL,
                    pricing_type VARCHAR2(30) NOT NULL,
                    quantity NUMBER DEFAULT 1 NOT NULL,
                    unit_amount NUMBER(12,2) NOT NULL,
                    total_amount NUMBER(12,2) NOT NULL,
                    currency VARCHAR2(3) DEFAULT 'BRL' NOT NULL,
                    status VARCHAR2(30) DEFAULT 'SELECTED' NOT NULL,
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
                    CONSTRAINT fk_reservation_addon_reservation FOREIGN KEY (reservation_id) REFERENCES fc_reservation(id),
                    CONSTRAINT fk_reservation_addon_session FOREIGN KEY (session_id) REFERENCES fc_checkin_session(id),
                    CONSTRAINT ck_reservation_addon_status CHECK (status IN ('SELECTED', 'REMOVED'))
                )
                """);
        executeIfMissing("CREATE INDEX ix_reservation_addon_session ON fc_reservation_addon(session_id)");
        executeIfMissing("CREATE INDEX ix_reservation_addon_reservation ON fc_reservation_addon(reservation_id)");
    }

    private void executeIfMissing(String sql) {
        try {
            jdbc.execute(sql);
        } catch (Exception ignored) {
        }
    }
}
